/** 取简称（裸文本），用于 tooltip 拼接 */
export function termLabel(key: keyof typeof TERMS | string): string {
  return TERMS[key]?.label ?? key;
}

/** 取一句话解释 */
export function termShort(key: keyof typeof TERMS | string): string {
  return TERMS[key]?.short ?? "";
}

/** 按分组整理，用于术语表 */
export function termsByGroup(): Record<string, TermDef[]> {
  const out: Record<string, TermDef[]> = {};
  for (const def of Object.values(TERMS)) {
    (out[def.group] ??= []).push(def);
  }
  return out;
}
